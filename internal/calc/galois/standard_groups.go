package galois

// Standard transitive permutation groups for degrees 3, 4, 5.

// TransitiveGroups3 returns the 2 transitive groups of degree 3.
func StandardS3() *PermGroup {
	g, _ := NewPermGroup("S3", 3, []Permutation{
		{1, 0, 2},    // (0 1)
		{1, 2, 0},    // (0 1 2)
	})
	return g
}

func StandardA3() *PermGroup {
	g, _ := NewPermGroup("A3", 3, []Permutation{
		{1, 2, 0},    // (0 1 2)
	})
	return g
}

// TransitiveGroups4 returns the 5 transitive groups of degree 4.
func StandardS4() *PermGroup {
	g, _ := NewPermGroup("S4", 4, []Permutation{
		{1, 0, 2, 3}, // (0 1)
		{1, 2, 3, 0}, // (0 1 2 3)
	})
	return g
}

func StandardA4() *PermGroup {
	g, _ := NewPermGroup("A4", 4, []Permutation{
		{1, 2, 0, 3}, // (0 1 2)
		{0, 2, 3, 1}, // (1 2 3)
	})
	return g
}

func StandardD4() *PermGroup {
	g, _ := NewPermGroup("D4", 4, []Permutation{
		{1, 2, 3, 0}, // r = (0 1 2 3)
		{3, 2, 1, 0}, // s = (0 3)(1 2)
	})
	return g
}

