package provenance

import (
	"fmt"
	"strings"

	"github.com/DovahkiinYuzuko/i-hate-decimal-calc/internal/calc/ast"
)

// TypstVisitor renders a derivation tree into Typst markup.
type TypstVisitor struct{}

// NewTypstVisitor creates a new TypstVisitor.
func NewTypstVisitor() *TypstVisitor {
	return &TypstVisitor{}
}

// RenderTypst renders the derivation steps into a multiline Typst math alignment block.
func (v *TypstVisitor) RenderTypst(root *DerivationNode) string {
	if root == nil {
		return "$ $\n"
	}

	ev := NewExplainVisitor()
	steps := ev.collectPresentableSteps(root)

	if len(steps) == 0 {
		beforeStr := nodeToTypst(root.Before)
		afterStr := nodeToTypst(root.After)
		return fmt.Sprintf("$ %s = %s $\n", beforeStr, afterStr)
	}

	var sb strings.Builder
	sb.WriteString("$\n")

	first := true
	for _, s := range steps {
		beforeStr := s.Before
		afterStr := s.After
		sym := relationSymbol(s.Relation)

		if first {
			sb.WriteString(fmt.Sprintf("  %s & %s %s \\\n", beforeStr, sym, afterStr))
			first = false
		} else {
			sb.WriteString(fmt.Sprintf("    & %s %s \\\n", sym, afterStr))
		}
	}

	sb.WriteString("$\n")
	return sb.String()
}

// RenderDocument renders the derivation tree into a standalone, compilable Typst document.
func (v *TypstVisitor) RenderDocument(root *DerivationNode, inputExpr string) string {
	var sb strings.Builder
	sb.WriteString("// Generated by ihd (Exact Arithmetic Calculator)\n")
	sb.WriteString("#set page(paper: \"a4\", margin: 2.5cm)\n")
	sb.WriteString("#set text(font: \"Linux Libertine\", size: 11pt)\n\n")
	sb.WriteString("= Mathematical Derivation Report\n\n")

	if inputExpr != "" {
		sb.WriteString(fmt.Sprintf("*Initial Expression:* $ %s $\n\n", inputExpr))
	} else if root != nil && root.Before != nil {
		sb.WriteString(fmt.Sprintf("*Initial Expression:* $ %s $\n\n", nodeToTypst(root.Before)))
	}

	sb.WriteString("== Derivation Steps\n\n")

	ev := NewExplainVisitor()
	steps := ev.collectPresentableSteps(root)

	if len(steps) == 0 {
		sb.WriteString("Expression was evaluated directly without intermediate rewrites.\n\n")
	} else {
		for _, s := range steps {
			sb.WriteString(fmt.Sprintf("=== Step %d: %s\n\n", s.StepNumber, s.Title))
			sb.WriteString(fmt.Sprintf("$ %s %s %s $\n\n", s.Before, relationSymbol(s.Relation), s.After))

			if len(s.Conditions) > 0 {
				sb.WriteString("*Conditions:* ")
				sb.WriteString(strings.Join(s.Conditions, ", "))
				sb.WriteString("\n\n")
			}

			if s.Certificate != "" {
				sb.WriteString(fmt.Sprintf("*Certificate:* `#text(fill: blue.darken(20%%))[%s]`\n\n", s.Certificate))
			}
		}
	}

	resStr := ""
	if root != nil && root.After != nil {
		resStr = nodeToTypst(root.After)
	} else if len(steps) > 0 {
		resStr = steps[len(steps)-1].After
	}

	sb.WriteString("== Final Result\n\n")
	sb.WriteString(fmt.Sprintf("#align(center)[#block(fill: luma(240), inset: 12pt, radius: 4pt)[*Result:* $ %s $]]\n", resStr))

	return sb.String()
}

func nodeToTypst(n ast.Node) string {
	if n == nil {
		return ""
	}
	return n.String()
}
